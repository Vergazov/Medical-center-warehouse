-- Генерация тестовых данных для таблицы items.
-- По умолчанию создаёт 10 000 записей с правдоподобными уникальными названиями.
-- Вызов: CALL seed_items_test_data();           -- 10 000 шт.
--        CALL seed_items_test_data(5000);       -- произвольное количество

DROP PROCEDURE IF EXISTS seed_items_test_data$$

CREATE DEFINER=`root`@`%` PROCEDURE seed_items_test_data(
    IN p_count INT UNSIGNED
)
BEGIN
    DECLARE v_count INT UNSIGNED DEFAULT 10000;

    IF p_count IS NOT NULL AND p_count > 0 THEN
        SET v_count = p_count;
    END IF;

    SET SESSION cte_max_recursion_depth = v_count;

    INSERT INTO items (name, unit_id, type_id, inv_number, serial_number, comment)
    WITH RECURSIVE nums AS (
        SELECT 1 AS n
        UNION ALL
        SELECT n + 1 FROM nums WHERE n < v_count
    ),
    item_rows AS (
        SELECT
            n,
            1 + MOD(n - 1, 6) AS type_id,
            CASE 1 + MOD(n - 1, 6)
                WHEN 1 THEN 1 + MOD(n - 1, 3)                          -- Медикаменты: шт / упаковка
                WHEN 2 THEN ELT(1 + MOD(n - 1, 3), 6, 7, 1)            -- Реактивы: мл / л / шт
                WHEN 3 THEN 1                                          -- Оборудование: шт
                WHEN 4 THEN 1                                          -- Мебель: шт
                WHEN 5 THEN 1 + MOD(n - 1, 3)                          -- Хозтовары
                ELSE 1 + MOD(n - 1, 2)                                 -- Расходники: шт / упаковка
            END AS unit_id,
            CASE 1 + MOD(n - 1, 6)
                -- Медикаменты
                WHEN 1 THEN CONCAT(
                    ELT(1 + MOD(n - 1, 40),
                        'Парацетамол', 'Ибупрофен', 'Амоксициллин', 'Цефтриаксон', 'Метформин',
                        'Омепразол', 'Лозартан', 'Амлодипин', 'Аторвастатин', 'Аспирин',
                        'Нурофен', 'Цитрамон', 'Анальгин', 'Но-шпа', 'Супрастин',
                        'Лоратадин', 'Амброксол', 'Ацикловир', 'Фуросемид', 'Варфарин',
                        'Каптоприл', 'Эналаприл', 'Бисопролол', 'Диклофенак', 'Кеторол',
                        'Ципрофлоксацин', 'Азитромицин', 'Кларитромицин', 'Доксициклин', 'Метронидазол',
                        'Флуконазол', 'Преднизолон', 'Дексаметазон', 'Инсулин гларгин', 'Глюкоза',
                        'Калия хлорид', 'Натрия хлорид', 'Гепарин', 'Фенотерол', 'Сальбутамол'
                    ),
                    ' ',
                    ELT(1 + MOD(n - 1, 5), 'таблетки', 'капсулы', 'раствор для инъекций', 'сироп', 'мазь'),
                    ' ',
                    ELT(1 + MOD(FLOOR((n - 1) / 5), 12),
                        '250 мг', '500 мг', '100 мг', '50 мг', '10 мг',
                        '5 мг', '2,5 мг', '1 г', '0,5 г', '20 мг/мл',
                        '40 мг/мл', '100 мг/мл'
                    ),
                    ', ',
                    ELT(1 + MOD(FLOOR((n - 1) / 60), 10),
                        '10 шт/уп', '20 шт/уп', '30 шт/уп', '50 шт/уп', '60 шт/уп',
                        '100 шт/уп', '5 амп×2 мл', '10 амп×1 мл', '1 фл×100 мл', '1 туба×15 г'
                    )
                )
                -- Реактивы
                WHEN 2 THEN CONCAT(
                    ELT(1 + MOD(n - 1, 25),
                        'Реагент для определения глюкозы', 'Реагент для определения холестерина',
                        'Реагент для определения креатинина', 'Реагент для определения мочевины',
                        'Реагент для определения билирубина', 'Реагент для определения АЛТ',
                        'Реагент для определения АСТ', 'Реагент для определения гемоглобина',
                        'Раствор Люголя', 'Раствор фуксина', 'Раствор Грамма',
                        'Среда питательная Mueller-Hinton', 'Среда Эндо', 'Среда Сабуро',
                        'Буферный раствор pH 7,4', 'Буферный раствор pH 4,0', 'Дистиллированная вода лабораторная',
                        'Формалин 10%', 'Спирт этиловый 70%', 'Перекись водорода 3%',
                        'Набор реагентов для ИФА', 'Калибратор биохимический', 'Контрольная сыворотка',
                        'Стандартный образец', 'Реагент для гематологического анализатора'
                    ),
                    ', ',
                    ELT(1 + MOD(FLOOR((n - 1) / 25), 8),
                        'фл. 50 мл', 'фл. 100 мл', 'фл. 250 мл', 'фл. 500 мл',
                        'фл. 1000 мл', 'набор 2×50 мл', 'набор 6×10 мл', 'картридж 200 тестов'
                    )
                )
                -- Оборудование
                WHEN 3 THEN CONCAT(
                    ELT(1 + MOD(n - 1, 20),
                        'Тонометр автоматический', 'Пульсоксиметр портативный', 'Стетоскоп акустический',
                        'Глюкометр', 'Термометр электронный', 'Небулайзер компрессорный',
                        'Дефибриллятор', 'Электрокардиограф', 'УЗИ-сканер портативный',
                        'Инфузионный насос', 'Шприцевой насос', 'Аппарат ИВЛ транспортный',
                        'Отсасыватель хирургический', 'Светильник операционный', 'Эндоскоп гибкий',
                        'Анализатор гематологический', 'Анализатор биохимический', 'Центрифуга лабораторная',
                        'Микроскоп бинокулярный', 'Весы медицинские напольные'
                    ),
                    ' ',
                    ELT(1 + MOD(FLOOR((n - 1) / 20), 6),
                        'модель Pro', 'модель Standard', 'модель Compact', 'модель Elite',
                        'серия MedLine', 'серия Diagnost'
                    ),
                    ' ',
                    ELT(1 + MOD(FLOOR((n - 1) / 120), 5),
                        '2023', '2024', '2025', 'rev.A', 'rev.B'
                    )
                )
                -- Мебель
                WHEN 4 THEN CONCAT(
                    ELT(1 + MOD(n - 1, 15),
                        'Кушетка медицинская смотровая', 'Кресло гинекологическое', 'Стол процедурный',
                        'Стул врача с колёсами', 'Шкаф медицинский металлический', 'Стеллаж для хранения',
                        'Тележка инструментальная', 'Тележка для медикаментов', 'Столик прикроватный',
                        'Каталка транспортная', 'Стол для перевязок', 'Барьер защитный складной',
                        'Система для внутривенных вливаний', 'Стойка для капельницы', 'Тумба прикроватная'
                    ),
                    ', ',
                    ELT(1 + MOD(FLOOR((n - 1) / 15), 6),
                        'белая', 'серая', 'синяя', 'нержавеющая сталь', 'ЛДСП белый', 'антивандальная'
                    ),
                    ', ',
                    ELT(1 + MOD(FLOOR((n - 1) / 90), 5),
                        '180×60 см', '190×70 см', '200×80 см', '4 полки', '3 ящика'
                    )
                )
                -- Хозтовары
                WHEN 5 THEN CONCAT(
                    ELT(1 + MOD(n - 1, 20),
                        'Средство дезинфицирующее', 'Моющее средство для полов', 'Салфетки бумажные',
                        'Полотенца бумажные', 'Мыло жидкое антибактериальное', 'Гель для рук антисептический',
                        'Пакеты для медотходов класс Б', 'Пакеты для медотходов класс А',
                        'Контейнер для острого инструмента', 'Ведро с педалью', 'Швабра плоская',
                        'Насадка для швабры', 'Перчатки хозяйственные', 'Губка абразивная',
                        'Средство для мытья стёкол', 'Освежитель воздуха', 'Салфетки влажные',
                        'Дозатор для мыла', 'Диспенсер для полотенец', 'Коврик входной'
                    ),
                    ' ',
                    ELT(1 + MOD(FLOOR((n - 1) / 20), 8),
                        '1 л', '5 л', '500 мл', '200 шт/уп', '100 шт/уп', '50 шт/уп', '10 л', '3 л'
                    )
                )
                -- Расходники
                ELSE CONCAT(
                    ELT(1 + MOD(n - 1, 30),
                        'Перчатки нитриловые нестерильные', 'Перчатки латексные стерильные',
                        'Маска медицинская одноразовая', 'Маска респиратор FFP2', 'Шапочка одноразовая',
                        'Халат одноразовый', 'Бахилы одноразовые', 'Шприц одноразовый стерильный',
                        'Игла инъекционная одноразовая', 'Катетер внутривенный', 'Система для переливания',
                        'Пластырь медицинский', 'Вата стерильная', 'Бинт марлевый стерильный',
                        'Салфетка марлевая', 'Шпатель деревянный', 'Зеркало гинекологическое одноразовое',
                        'Пелёнка одноразовая', 'Простыня одноразовая', 'Салфетка дезинфицирующая',
                        'Тампон ватный стерильный', 'Пробирка вакуумная', 'Контейнер для анализов',
                        'Мочеприёмник', 'Лейкопластырь фиксирующий', 'Жгут кровоостанавливающий',
                        'Манжета для тонометра', 'Электрод ЭКГ одноразовый', 'Наконечник для глюкометра',
                        'Канюля назальная'
                    ),
                    ' ',
                    ELT(1 + MOD(FLOOR((n - 1) / 30), 8),
                        'размер XS', 'размер S', 'размер M', 'размер L', 'размер XL',
                        '2 мл', '5 мл', '10 мл'
                    ),
                    ', ',
                    ELT(1 + MOD(FLOOR((n - 1) / 240), 6),
                        '50 шт/уп', '100 шт/уп', '200 шт/уп', '10 шт/уп', '25 шт/уп', '500 шт/уп'
                    )
                )
            END AS base_name,
            CASE 1 + MOD(n - 1, 6)
                WHEN 3 THEN CONCAT('INV-EQ-', LPAD(n, 5, '0'))
                ELSE NULL
            END AS inv_number,
            CASE 1 + MOD(n - 1, 6)
                WHEN 3 THEN CONCAT('SN-', DATE_FORMAT(NOW(), '%y%m'), '-', LPAD(n, 5, '0'))
                ELSE NULL
            END AS serial_number,
            CASE 1 + MOD(n - 1, 6)
                WHEN 1 THEN 'Тестовая запись: медикамент'
                WHEN 2 THEN 'Тестовая запись: реактив для лаборатории'
                WHEN 3 THEN 'Тестовая запись: медицинское оборудование'
                WHEN 4 THEN 'Тестовая запись: медицинская мебель'
                WHEN 5 THEN 'Тестовая запись: хозяйственный товар'
                ELSE 'Тестовая запись: расходный материал'
            END AS base_comment
        FROM nums
    )
    SELECT
        CONCAT(base_name, ', арт. ТМ-', LPAD(n, 5, '0')) AS name,
        unit_id,
        type_id,
        inv_number,
        serial_number,
        base_comment AS comment
    FROM item_rows;

    SELECT v_count AS inserted_count, 'OK' AS status;
END$$

